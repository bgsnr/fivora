-- Users policies: pemilik profil hanya membaca dirinya sendiri;
-- petugas/admin dapat membaca profil lain untuk menampilkan nama pemohon
DROP POLICY IF EXISTS "Fivora users read own profile" ON public.users;
CREATE POLICY "Fivora users read own profile" ON public.users
  FOR SELECT USING (auth_user_id = auth.uid());

DROP POLICY IF EXISTS "Fivora staff can read all profiles" ON public.users;
CREATE POLICY "Fivora staff can read all profiles" ON public.users
  FOR SELECT USING (
    EXISTS (
      SELECT 1 FROM public.get_current_user_profile() p
      WHERE p.role IN ('petugas', 'admin')
    )
  );

-- RLS Policies for reservations:
DROP POLICY IF EXISTS "Users can read own or approved reservations, staff can read all" ON public.reservations;
CREATE POLICY "Users can read own or approved reservations, staff can read all" ON public.reservations
  FOR SELECT USING (
    status = 'disetujui'
    OR user_id IN (SELECT user_id FROM public.get_current_user_profile())
    OR EXISTS (
      SELECT 1 FROM public.get_current_user_profile() p
      WHERE p.role IN ('petugas', 'admin')
    )
  );

DROP POLICY IF EXISTS "Users can insert own pending reservation" ON public.reservations;
CREATE POLICY "Users can insert own pending reservation" ON public.reservations
  FOR INSERT WITH CHECK (
    user_id IN (SELECT user_id FROM public.get_current_user_profile())
    AND status = 'menunggu'
  );

DROP POLICY IF EXISTS "Users can cancel own reservation, staff can update status" ON public.reservations;
CREATE POLICY "Users can cancel own reservation, staff can update status" ON public.reservations
  FOR UPDATE USING (
    user_id IN (SELECT user_id FROM public.get_current_user_profile())
    OR EXISTS (
      SELECT 1 FROM public.get_current_user_profile() p
      WHERE p.role = 'petugas'
    )
  )
  WITH CHECK (
    (
      user_id IN (SELECT user_id FROM public.get_current_user_profile())
      AND status = 'dibatalkan'
    )
    OR EXISTS (
      SELECT 1 FROM public.get_current_user_profile() p
      WHERE p.role = 'petugas'
    )
  );
