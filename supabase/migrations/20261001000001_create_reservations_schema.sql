-- MODUL ALYSSA AKAN MELENGKAPI kolom lainnya (nim_nip, jenis_pengguna,
-- verifikasi admin, dll). Jangan menghapus kolom dasar ini.
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_user_id UUID UNIQUE,
  name VARCHAR(255),
  email VARCHAR(255) UNIQUE,
  role VARCHAR(20) NOT NULL DEFAULT 'pengguna'
    CHECK (role IN ('pengguna', 'petugas', 'admin')),
  status VARCHAR(20) NOT NULL DEFAULT 'aktif'
    CHECK (status IN ('menunggu', 'aktif', 'ditolak')),
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 2. Tabel Reservations (Modul Bagas)
CREATE TABLE IF NOT EXISTS public.reservations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  facility_id BIGINT NOT NULL REFERENCES public.facilities(id) ON DELETE CASCADE,
  reservation_date DATE NOT NULL,
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  purpose TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'menunggu' 
    CHECK (status IN ('menunggu', 'disetujui', 'ditolak', 'dibatalkan')),
  rejection_reason TEXT,
  processed_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  processed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- Constraint EXCLUDE (Chapter 2 & AGENTS.md):
-- Mencegah dua reservasi berstatus 'disetujui' overlap pada fasilitas & tanggal yang sama.
-- HANYA berlaku untuk status = 'disetujui' (status 'menunggu' tetap boleh bertabrakan di antrean).
ALTER TABLE public.reservations
ADD CONSTRAINT no_overlapping_approved_reservations
EXCLUDE USING gist (
  facility_id WITH =,
  reservation_date WITH =,
  tsrange(
    (reservation_date + start_time),
    (reservation_date + end_time)
  ) WITH &&
) WHERE (status = 'disetujui');

-- Indexing
CREATE INDEX IF NOT EXISTS idx_reservations_facility_date 
  ON public.reservations(facility_id, reservation_date);
CREATE INDEX IF NOT EXISTS idx_reservations_facility_date_status
  ON public.reservations(facility_id, reservation_date, status);
CREATE INDEX IF NOT EXISTS idx_reservations_user_id 
  ON public.reservations(user_id);
CREATE INDEX IF NOT EXISTS idx_reservations_status_created 
  ON public.reservations(status, created_at);

-- Enable RLS on reservations
ALTER TABLE public.reservations ENABLE ROW LEVEL SECURITY;

-- Helper function to get current user profile based on auth.uid()
CREATE OR REPLACE FUNCTION public.get_current_user_profile()
RETURNS TABLE (user_id BIGINT, role VARCHAR) AS $$
BEGIN
  RETURN QUERY
  SELECT u.id, u.role
  FROM public.users u
  WHERE u.auth_user_id = auth.uid()
  LIMIT 1;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

